import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const sharp = process.env.QM_SHARP ? require(process.env.QM_SHARP) : require('sharp');
const root=path.resolve(import.meta.dirname,'..');
const raw=path.join(root,'art/raw');
const out=path.join(root,'art/optimized');
await fs.mkdir(out,{recursive:true});
const portraits=['shen','li','wen','lu','tang','han','qinyan','liu','bailu','mojiu','aman','hua','new_qinglan_m','new_qinglan_f','new_chixiao_m','new_chixiao_f','new_free_m','new_free_f'];
const data={};
for(const name of (await fs.readdir(raw)).filter(n=>n.endsWith('.png'))){
 const id=path.basename(name,'.png');const src=path.join(raw,name);
 const buf=await sharp(src).resize({width:portraits.includes(id)?640:1000,withoutEnlargement:true}).webp({quality:82,effort:6}).toBuffer();
 await fs.writeFile(path.join(out,id+'.webp'),buf);data[id]='data:image/webp;base64,'+buf.toString('base64');
 if(portraits.includes(id)){
  const {width,height}=await sharp(src).metadata();const size=Math.round(width*.64);
  const avatar=await sharp(src).extract({left:Math.round((width-size)/2),top:Math.max(0,Math.round(height*.07)),width:size,height:Math.min(size,height)}).resize(144,172,{fit:'cover'}).webp({quality:85}).toBuffer();
  await fs.writeFile(path.join(out,id+'-avatar.webp'),avatar);data[id+'_avatar']='data:image/webp;base64,'+avatar.toString('base64');
 }
}
await fs.writeFile(path.join(root,'assets/ui/art-data.ts'),'// Generated by npm run art. Bundled URLs work inside the engine without external asset paths.\nexport const ART: Record<string,string> = '+JSON.stringify(data)+';\n');
console.log('Built '+Object.keys(data).length+' optimized images');

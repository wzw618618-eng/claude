/** 字符画 → SVG 路径（同一行连续的格子合成一段） */
function path(rows, ch) {
  let d = '';
  rows.forEach((r, y) => {
    let x = 0;
    while (x < r.length) {
      if (r[x] !== ch) { x++; continue; }
      const x0 = x;
      while (x < r.length && r[x] === ch) x++;
      d += `M${x0} ${y}h${x - x0}v1h${x0 - x}z`;
    }
  });
  return d;
}

/** 图标 → SVG 内部内容和 viewBox 尺寸 */
export function iconSvg(name) {
  const rows = ICONS[name];
  if (!rows) throw new Error(`没有像素图标 ${name}`);
  const w = Math.max(...rows.map((r) => r.length));
  const main = path(rows, '#');
  const soft = path(rows, '+');
  return { size: Math.max(w, rows.length), body: `<path d="${main}"/>${soft ? `<path opacity=".5" d="${soft}"/>` : ''}` };
}
